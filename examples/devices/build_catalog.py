"""Bundle exact RLE and compact thumbnails for the offline browser catalog.

Run with the project's Python from any directory when a source RLE changes.
The standalone editor loads a data script only when that device is selected.
"""
import hashlib
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from life.formats import parse_rle

WEB = ROOT / 'web'
LOGIC = ROOT / 'examples/logic'
def write(path, text):
    path.write_text(text, encoding='utf-8', newline='\n')

def thumbnail(cells, width, height):
    span = max(width, height)
    cols, rows = max(1, round(64*width/span)), max(1, round(64*height/span))
    bins = [0]*(cols*rows)
    for x, y in cells:
        bins[(y*rows//height)*cols + x*cols//width] += 1
    peak = math.log1p(max(bins, default=0)) or 1
    return dict(width=cols, height=rows, levels=''.join(format(max(1, round(15*math.log1p(n)/peak)), 'x') if n else '0' for n in bins))

def build():
    additions = []
    devices = json.loads(Path(__file__).with_name('catalog.json').read_text('utf-8'))
    for p in devices:
        path = WEB / 'patterns' / (p['id']+'.rle')
        text = path.read_text('utf-8')
        # Thumbnail shows the physical footprint, ignoring the import padding.
        bare = '\n'.join(line for line in text.splitlines() if not line.startswith('#C LIFE '))
        state = parse_rle(bare)
        assert (state.width, state.height, len(state.cells)) == (p['width'],p['height'],p['population'])
        p.update(preserveBoard=True, preview=thumbnail(state.cells,state.width,state.height),
                 sha256=hashlib.sha256(path.read_bytes()).hexdigest(), file='patterns/'+path.name)
        write(path.with_suffix('.js'), '// Generated data for the offline catalog. See THIRD_PARTY.md.\n' +
              'window.LIFE_PATTERN_ASSETS = window.LIFE_PATTERN_ASSETS || Object.create(null);\n' +
              f'window.LIFE_PATTERN_ASSETS[{json.dumps(p["id"])}] = {json.dumps(text)};\n')
        additions.append(p)

    manifest = json.loads((LOGIC / 'extended-truth-tables.json').read_text('utf-8'))
    for demo in manifest['demos']:
        read = demo['checkpoints'][-1]
        variants = []
        for case in demo['cases']:
            rle = (LOGIC / case['rle']).read_text('utf-8')
            pop = len(parse_rle(rle).cells)
            out = case['outputs'][-1]
            label = ', '.join(f'{pin} = {bit}' for pin,bit in zip(demo['pins'],case['inputs']))
            variants.append(dict(label=label, inputs=case['inputs'], population=pop, rle=rle,
                verification=dict(kind='logic',generation=read['generation'],output_roi=read['output_roi'],
                                  expected_output=out,expected_population=out*len(read['one_cells']),signal=read['signal'])))
        default = next(i for i,v in enumerate(variants) if v['verification']['expected_output'] and v['population'])
        # A nonempty default gives one meaningful preview without duplicating
        # four versions as unrelated entries in the catalog.
        best = variants[default]
        entry = dict(id='logic-'+demo['id'],name=demo['label'],type='LOGIC CIRCUIT',
            note=f"{demo['description']} Read generation {read['generation']}.",
            description=demo['description']+' Single-use circuit. Select the inputs before starting.',
            width=manifest['width'],height=manifest['height'],population=best['population'],
            search=' '.join(['logic gate',demo['label'],demo['id'],*demo['pins']]),
            provenance='original',source='examples/logic/EXTENDED.md',preserveBoard=True,
            defaultVariant=default,variants=variants)
        g = parse_rle(best['rle'])
        entry['preview'] = thumbnail(g.cells,g.width,g.height)
        additions.append(entry)
    write(WEB/'device-library.js', '// Generated by examples/devices/build_catalog.py.\nwindow.LIFE_PATTERNS.push(...' +
          json.dumps(additions, ensure_ascii=False, separators=(',',':')) + ');\n')
    original = (WEB/'patterns.js').read_text('utf-8').split('window.LIFE_PATTERNS = ',1)[1].strip().removesuffix(';')
    write(WEB/'patterns.json', json.dumps(json.loads(original)+additions,ensure_ascii=False,separators=(',',':'))+'\n')
    print(f'Built {len(devices)} local assets, {len(additions)-len(devices)} circuit cards; {len(json.loads(original))+len(additions)} total entries.')

if __name__ == '__main__':
    build()
